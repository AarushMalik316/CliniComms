/**
 * Genuine CRC-16-CCITT (False / 0x1021 polynomial, 0xFFFF initial seed)
 * Calculated over Packet Type (byte 3) through Payload (byte 17).
 */
export function crc16ccitt(data: Uint8Array): number {
  let crc = 0xffff;
  for (let i = 0; i < data.length; i++) {
    crc ^= data[i] << 8;
    for (let bit = 0; bit < 8; bit++) {
      if ((crc & 0x8000) !== 0) {
        crc = ((crc << 1) ^ 0x1021) & 0xffff;
      } else {
        crc = (crc << 1) & 0xffff;
      }
    }
  }
  return crc & 0xffff;
}
